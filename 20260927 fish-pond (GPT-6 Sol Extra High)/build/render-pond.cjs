const {chromium}=require('C:/Users/admin/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist','--use-angle=swiftshader']});
 const page=await browser.newPage({viewport:{width:1280,height:900},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const url=pathToFileURL(path.join(__dirname,'..','fish-pond.html')).href;
 await page.goto(url+'?paused&t=4');
 await page.waitForFunction(()=>window.pond?.state.renderedFrames>0||!document.getElementById('err').hidden,null,{timeout:90000});
 await page.waitForTimeout(1200);
 console.log(JSON.stringify({desktop:true,errors,errorText:await page.locator('#err').textContent()}));
 await page.screenshot({path:path.join(__dirname,'pond-improved-desktop.png')});
 if(errors.length||await page.locator('#err').isVisible()){await browser.close();process.exit(1);}
 const start=await page.evaluate(()=>window.pond.state);
 await page.locator('#light-toggle').click();
 await page.locator('#light-picker [data-light="golden"]').click();
 await page.waitForFunction(n=>window.pond.state.renderedFrames>n,start.renderedFrames,{timeout:90000});
 assert.equal(await page.locator('#light-badge').textContent(),'Golden hour');
 assert.equal(await page.evaluate(()=>window.pond.state.time),start.time);
 await page.screenshot({path:path.join(__dirname,'pond-improved-golden.png')});
 await page.locator('#light-toggle').click();
 await page.locator('#light-picker [data-light="morning"]').click();
 await page.waitForFunction(()=>window.pond.state.light==='morning'&&document.getElementById('light-badge').textContent==='Morning light');
 await page.locator('#about-open').click();
 assert(await page.locator('#about-dialog').isVisible());
 await page.locator('#about-close').click();
 assert(!await page.locator('#about-dialog').isVisible());
 console.log(JSON.stringify({pausedLighting:true,about:true}));
 await page.setViewportSize({width:390,height:844});
 await page.goto(url+'?paused&t=4');
 await page.waitForFunction(()=>window.pond?.state.renderedFrames>0,null,{timeout:90000});
 await page.waitForTimeout(1000);
 await page.screenshot({path:path.join(__dirname,'pond-improved-mobile.png')});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
 await page.locator('#settings-toggle').click();
 assert(await page.locator('#settings').isVisible());
 await page.locator('#close-settings').click();
 await page.locator('#pause').click();
 await page.locator('#c').click({position:{x:195,y:422}});
 await page.waitForFunction(()=>window.pond.state.ripples===1,null,{timeout:90000});
 await page.locator('#feed').click();
 await page.locator('#c').click({position:{x:195,y:422}});
 await page.waitForFunction(()=>window.pond.state.feedings===1,null,{timeout:90000});
 const mobile=await page.evaluate(()=>window.pond.state);
 assert(mobile.time>0);assert(mobile.pellets>0);
 assert.equal(errors.length,0);assert(!await page.locator('#err').isVisible());
 console.log(JSON.stringify({mobile:true,ripples:mobile.ripples,feedings:mobile.feedings,pellets:mobile.pellets,errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
