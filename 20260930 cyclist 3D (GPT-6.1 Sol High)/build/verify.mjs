import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
process.chdir(path.dirname(fileURLToPath(import.meta.url)));
const require=createRequire(import.meta.url);
const {chromium}=require('C:/Users/admin/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const browser=await chromium.launch({channel:'msedge',headless:true,args:['--enable-unsafe-swiftshader']});
const errors=[];
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  page.on('pageerror',error=>errors.push(error.message));
  page.on('response',response=>{if(response.status()>=400)errors.push(`${response.status()} ${response.url()}`);});
  await page.goto('http://127.0.0.1:5173',{waitUntil:'domcontentloaded',timeout:60000});
  await page.waitForFunction(()=>window.cadenceStudio?.getState().ready,{},{timeout:20000});
  const initial=await page.evaluate(()=>window.cadenceStudio.getState());
  assert.equal(initial.clips,1,'GLB should export one combined riding clip');
  await page.waitForTimeout(300);
  assert.ok((await page.evaluate(()=>window.cadenceStudio.getState())).animationTime>initial.animationTime);
  await page.getByRole('button',{name:'Pause cycling',exact:true}).click();
  const paused=await page.evaluate(()=>window.cadenceStudio.getState().animationTime);
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(()=>window.cadenceStudio.getState().animationTime),paused,'Pause should freeze the model');
  await page.locator('#cadence').fill('120');
  assert.equal(await page.evaluate(()=>window.cadenceStudio.getState().rpm),120);
  assert.equal(await page.locator('#speed').textContent(),'49.3');
  await page.getByRole('button',{name:'Side',exact:true}).click();
  await page.waitForTimeout(600);
  assert.equal(await page.evaluate(()=>window.cadenceStudio.getState().view),'side');
  await page.getByRole('button',{name:'Front',exact:true}).click();
  await page.waitForTimeout(600);
  await page.getByRole('button',{name:'Reset camera',exact:true}).click();
  await page.waitForTimeout(600);
  await page.locator('#cadence').fill('80');
  await fs.mkdir('.sites-runtime',{recursive:true});
  await page.screenshot({path:'.sites-runtime/desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Auto orbit',exact:true}).click();
  assert.equal(await page.evaluate(()=>window.cadenceStudio.getState().orbit),true);
  await page.getByRole('button',{name:'Reset camera',exact:true}).click();
  assert.equal(await page.evaluate(()=>window.cadenceStudio.getState().orbit),false);
  await page.getByRole('button',{name:'Play cycling',exact:true}).click();
  assert.equal(await page.evaluate(()=>window.cadenceStudio.getState().playing),true);
  const downloads=await page.evaluate(async()=>Promise.all(['./assets/cyclist.glb','./assets/cyclist.blend'].map(async url=>{const r=await fetch(url);return {url,status:r.status,size:(await r.arrayBuffer()).byteLength};})));
  downloads.forEach(r=>{assert.equal(r.status,200);assert.ok(r.size>10000);});
  const nativeWebMCP=await page.evaluate(()=>!!document.modelContext?.registerTool);
  await page.close();
  console.log('Desktop playback and camera controls passed.');
  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,reducedMotion:'reduce'});
  mobile.on('pageerror',error=>errors.push(error.message));
  await mobile.goto('http://127.0.0.1:5173',{waitUntil:'domcontentloaded',timeout:60000});
  await mobile.waitForFunction(()=>window.cadenceStudio?.getState().ready,{},{timeout:20000});
  assert.equal(await mobile.evaluate(()=>window.cadenceStudio.getState().playing),false,'Reduced motion should start paused');
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile must not scroll horizontally');
  await mobile.screenshot({path:'.sites-runtime/mobile.png',fullPage:true});
  assert.deepEqual(errors,[],'Page should have no missing assets or uncaught exceptions');
  console.log(JSON.stringify({passed:true,initial,downloads,nativeWebMCP,screenshots:['.sites-runtime/desktop.png','.sites-runtime/mobile.png']},null,2));
}finally{await browser.close();}
